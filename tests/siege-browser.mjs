import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5174/',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Begin the siege'}).click();
await page.waitForFunction(()=>window.__ASHENWATCH__.model.defenders.length===12);
await page.locator('#defender-count').filter({hasText:'12 / 36 defenders'}).waitFor();
await page.locator('#tower-count').filter({hasText:'2 / 3 towers'}).waitFor();
assert.ok(await page.evaluate(()=>window.__ASHENWATCH__.scene.cameras.main.zoom<1));
await page.evaluate(()=>window.__ASHENWATCH__.model.nextXp=10000);
await page.screenshot({path:'test-results/siege-defenders-desktop.png'});
await page.locator('#tower-index summary').click();await page.locator('[data-tower="0"]').click();
await page.waitForFunction(()=>{const m=window.__ASHENWATCH__.model,t=m.towers[0];return Math.hypot(m.hero.x-t.x,m.hero.y-t.y)<115;});
await page.locator('#context').filter({hasText:'Reinforce Westwatch'}).waitFor();await page.locator('#interact').click();
await page.waitForFunction(()=>window.__ASHENWATCH__.model.towers[0].level===2);
await page.evaluate(()=>window.__ASHENWATCH__.model.gold=200);
await page.locator('#tower-index summary').click();await page.locator('[data-tower="2"]').click();
await page.waitForFunction(()=>{const m=window.__ASHENWATCH__.model,t=m.towers[2];return Math.hypot(m.hero.x-t.x,m.hero.y-t.y)<115;});
await page.locator('#interact').click();await page.waitForFunction(()=>window.__ASHENWATCH__.model.towers[2].built);
await page.locator('#tower-count').filter({hasText:'3 / 3 towers'}).waitFor();
await page.evaluate(()=>{const m=window.__ASHENWATCH__.model;for(const u of m.units)if(u.campId)m.damage(u,u.hp);m.hero.hp=m.hero.maxHp;});
await page.locator('#blessings').filter({hasText:'Stoneheart'}).waitFor();await page.locator('#blessings').filter({hasText:'Predator sigil'}).waitFor();await page.locator('#blessings').filter({hasText:'Pack oath'}).waitFor();
assert.ok(await page.evaluate(()=>window.__ASHENWATCH__.model.defenders.every(u=>u.damage>16&&u.maxHp>=120)));
await page.screenshot({path:'test-results/siege-towers-buffs.png'});
const bosses=['Ashhorn, the Breachmaker','The Rime Oracle','The Hollow King'];
const skins=['ashhorn','rimewitch','hollowking'];
for(let stage=0;stage<3;stage++){
  await page.evaluate(()=>{const m=window.__ASHENWATCH__.model;m.hero.hp=m.hero.maxHp;m.stageWave=2;m.waveTimer=0;});
  await page.locator('#boss-name').filter({hasText:bosses[stage]}).waitFor();
  const boss=await page.evaluate(()=>{const m=window.__ASHENWATCH__.model,b=m.units.find(u=>u.kind==='boss');b.x=865;b.y=515;b.specialCooldown=0;b.summonCooldown=0;m.hero.x=970;m.hero.y=525;m.stop();return b.id;});
  await page.waitForFunction(id=>window.__ASHENWATCH__.model.hazards.some(h=>h.sourceId===id),boss);
  assert.equal(await page.evaluate(id=>window.__ASHENWATCH__.scene.children.list.find(a=>a.getData?.('unitId')===id).texture.key,boss),skins[stage]);
  await page.waitForFunction(()=>window.__ASHENWATCH__.model.units.some(u=>u.summoned));
  await page.screenshot({path:`test-results/siege-phase-${stage+1}.png`});
  await page.evaluate(id=>{const m=window.__ASHENWATCH__.model,b=m.units.find(u=>u.id===id);m.damage(b,b.hp);m.hero.x=490;m.hero.y=660;for(let i=0;i<110;i++){for(const u of m.units)if(u.kind==='enemy'&&u.lane>=0)m.damage(u,u.hp);m.update(.05,{x:0,y:0,attack:false});}},boss);
  if(stage<2){await page.waitForFunction(s=>window.__ASHENWATCH__.model.stage===s,stage+1);await page.locator('#siege-stage').filter({hasText:`0${stage+2} / 03`}).waitFor();assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.model.stageState),'prepare');}
}
await page.getByRole('button',{name:'Enter the next age'}).waitFor();assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.model.defeatedBosses.length),3);
await page.screenshot({path:'test-results/siege-three-phase-victory.png'});
await page.getByRole('button',{name:'Enter the next age'}).click();await page.waitForFunction(()=>window.__ASHENWATCH__.model.stage===0&&window.__ASHENWATCH__.model.age===2);
assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.model.artifacts.length),0);
await page.setViewportSize({width:390,height:844});await page.waitForFunction(()=>window.__ASHENWATCH__.scene.scale.width===390);
await page.locator('#siege-stage').waitFor({state:'visible'});
await page.screenshot({path:'test-results/siege-defenders-mobile.png'});
await page.locator('#tower-index summary').click();await page.locator('[data-tower="0"]').click();assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.model.order?.point.x),600);
const box=await page.locator('.objectives').boundingBox();assert.ok(box.y+box.height<650,'Mobile sidebar protects lower combat area');
assert.deepEqual(errors,[],'No browser exceptions');
console.log('Siege browser checks passed: starting army and towers, fortification commands, upgrades and rebuilding, shared buffs, three boss skins and summons, phase recovery, victory, next age, and mobile HUD.');
await browser.close();
