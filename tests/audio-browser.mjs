import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5174/',{waitUntil:'networkidle'});
  assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.audio.diagnostics.state),'locked');
  await page.getByRole('button',{name:'Begin the siege'}).click();
  await page.evaluate(()=>{const m=window.__ASHENWATCH__.model;m.waveTimer=m.recruitTimer=m.nextXp=100000;});
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.ready,null,{timeout:60000});
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.rms>.001);
  await page.evaluate(()=>{const m=window.__ASHENWATCH__.model;m.waveTimer=0;m.update(.05,{x:0,y:0,attack:false});m.waveTimer=100000;});
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.mix.battle>.4);
  await page.evaluate(()=>{const m=window.__ASHENWATCH__.model;m.stageWave=2;m.waveTimer=0;m.update(.05,{x:0,y:0,attack:false});});
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.mix.boss>.4);
  await page.getByRole('button',{name:'Pause game'}).click();
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.mix.boss<.1);
  await page.locator('#music-volume').evaluate(e=>{e.value='70';e.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.audio.musicVolume),.7);
  assert.equal(await page.locator('#music-level').textContent(),'70%');
  await page.screenshot({path:'test-results/music-settings-desktop.png'});
  await page.getByRole('button',{name:'Mute music'}).click();
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.rms<.0001);
  assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.audio.enabled),true);
  await page.getByRole('button',{name:'Return to the valley'}).click();
  await page.keyboard.press('q');await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.rms>.001);
  assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.audio.musicEnabled),false);
  await page.getByRole('button',{name:'Pause game'}).click();
  await page.getByRole('button',{name:'Enable music'}).click();
  await page.getByRole('button',{name:'Return to the valley'}).click();
  await page.getByRole('button',{name:'Toggle sound'}).click();
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.rms<.0001);
  await page.getByRole('button',{name:'Toggle sound'}).click();
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.rms>.001);
  // Exercise the visibility handler while retaining the browser's actual audio clock.
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.state==='suspended');
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>false});document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForFunction(()=>window.__ASHENWATCH__.audio.diagnostics.state==='running');
  await page.getByRole('button',{name:'Return to the valley'}).click();
  await page.getByRole('button',{name:'How to play'}).click();
  await page.getByRole('button',{name:'Start a fresh expedition'}).click();
  assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.audio.diagnostics.loops),3);
  await page.setViewportSize({width:320,height:844});
  await page.getByRole('button',{name:'Pause game'}).click();
  await page.screenshot({path:'test-results/music-settings-mobile.png'});
  const box=await page.locator('.audio-settings').boundingBox();assert.ok(box.x>=0&&box.x+box.width<=320);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.audio.musicVolume),.7);
  assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.audio.musicEnabled),true);
  assert.equal(await page.evaluate(()=>window.__ASHENWATCH__.audio.diagnostics.state),'locked');
  assert.deepEqual(errors,[]);
  console.log('Audio checks passed: gesture start, audible output, wave/boss layers, pause, independent mute, effects, volume, hidden tabs, persistence, restart, and mobile settings.');
}finally{await browser.close();}
